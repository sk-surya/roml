/// Stable opaque identifier for a semantic conflict atom.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct ConflictAtomId(pub u64);

/// Reference to one compiled restriction.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum CompiledRestrictionRef {
    /// Lower side of a compiled row.
    ConstraintLower(CompiledConstraintId),
    /// Upper side of a compiled row.
    ConstraintUpper(CompiledConstraintId),
    /// Lower bound side of a compiled variable.
    VariableLower(CompiledVariableId),
    /// Upper bound side of a compiled variable.
    VariableUpper(CompiledVariableId),
    /// A compiled entity generated by a grouped semantic construct.
    Entity(CompiledEntityRef),
}

/// Semantic restriction universe used by a reducer and oracle.
#[derive(Clone, Debug, PartialEq)]
pub struct SemanticConflictUniverse {
    /// Exact compiled state this universe belongs to.
    pub compilation_id: CompilationId,
    /// Semantic atoms.
    pub atoms: Vec<SemanticRestrictionAtom>,
    /// Compiled restrictions represented by the atoms.
    pub compiled_restrictions: Vec<CompiledRestrictionRef>,
    /// Grouping policy used to form atoms.
    pub grouping: ConflictGrouping,
}

/// One semantically toggleable restriction atom.
#[derive(Clone, Debug, PartialEq)]
pub struct SemanticRestrictionAtom {
    /// Stable atom identifier.
    pub id: ConflictAtomId,
    /// Semantic class.
    pub kind: ConflictAtomKind,
    /// Original semantic origin.
    pub origin: ConflictOrigin,
    /// Compiled restrictions covered by this atom.
    pub compiled_restrictions: Vec<CompiledRestrictionRef>,
    /// Disable operation.
    pub disable: RestrictionTogglePlan,
    /// Restore operation.
    pub restore: RestrictionTogglePlan,
    /// Historical member data.
    pub snapshot: ConflictMemberSnapshot,
}

/// Selection of atoms to retain for one oracle check.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RestrictionSelection {
    /// Exact universe compilation identity.
    pub compilation_id: CompilationId,
    /// Selected atom identifiers.
    pub atom_ids: Vec<ConflictAtomId>,
}

/// Oracle budget for one feasibility check.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct OracleBudget {
    /// Optional backend time limit in milliseconds.
    pub time_limit_ms: Option<u64>,
}

/// Feasibility oracle used by the portable reducer.
pub trait FeasibilityOracle {
    /// Exact compiled state checked by this oracle.
    fn compilation_id(&self) -> CompilationId;

    /// Check one semantic restriction selection.
    fn check(
        &mut self,
        selection: &RestrictionSelection,
        budget: &OracleBudget,
    ) -> Result<FeasibilityOutcome, BackendError>;
}

/// Native conflict request passed through a qualified backend boundary.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NativeConflictRequest {
    /// Exact compiled state requested.
    pub compilation_id: CompilationId,
}

/// Native compiled-membership conflict result.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NativeConflict {
    /// Exact compiled state producing the evidence.
    pub compilation_id: CompilationId,
    /// Compiled restrictions reported by the provider.
    pub members: Vec<CompiledRestrictionRef>,
}

/// Optional backend capability boundary for infeasibility analysis.
pub trait InfeasibilityOracleFactory {
    /// Oracle type created by this backend.
    type Oracle: FeasibilityOracle;

    /// Create an isolated oracle over one exact backend snapshot.
    fn spawn_infeasibility_oracle(
        &self,
        snapshot: &BackendSnapshot,
        universe: &SemanticConflictUniverse,
    ) -> Result<Self::Oracle, BackendError>;

    /// Request native compiled-membership evidence.
    fn native_conflict(
        &self,
        request: &NativeConflictRequest,
    ) -> Result<NativeConflict, BackendError>;
}

